package entity

// 数据库索引优化说明
// 本文件定义了所有需要优化的索引，以提高查询性能
//
// 索引优化原则：
// 1. 为WHERE子句中经常使用的字段添加索引
// 2. 为JOIN操作的关联字段添加索引
// 3. 为ORDER BY和GROUP BY使用的字段添加索引
// 4. 为经常用于过滤的状态字段添加索引
// 5. 为关联表添加唯一联合索引，防止重复数据
//
// 注意：GORM的索引定义在实体字段的gorm tag中，例如：
// - index: 普通索引
// - uniqueIndex: 唯一索引
// - index:name1,index2:name2: 多个索引
// - index:,unique: 唯一索引
// - index:idx_name,priority:2: 指定索引名称和优先级

// 索引优化清单：
//
// 1. AA01 (用户表)
//    - AAA010 (状态) - 添加索引：用于按状态筛选用户
//    - AAA016 (创建人) - 添加索引：用于查询创建人创建的用户
//    - AAA017 (修改人) - 添加索引：用于查询修改人修改的用户
//    - AAA013 (最后登录时间) - 已有索引 ✓
//    - AAA002 (邮箱) - 已有唯一索引 ✓
//    - AAA003 (手机号) - 已有唯一索引 ✓
//
// 2. AA05 (角色表)
//    - AAE005 (状态) - 添加索引：用于按状态筛选角色
//    - AAE002 (角色标识) - 已有唯一索引 ✓
//
// 3. AA06 (权限表)
//    - AAF007 (状态) - 添加索引：用于按状态筛选权限
//    - AAF010 (分类) - 添加索引：用于按分类筛选权限
//    - AAF004+AAF005 (资源路径+请求方法) - 添加联合索引：用于快速查找权限
//    - AAF002 (权限标识) - 已有唯一索引 ✓
//
// 4. AA07 (用户角色关联表)
//    - AAG001+AAG002 (用户ID+角色ID) - 添加唯一联合索引：防止重复分配
//    - AAG001 (用户ID) - 已有索引 ✓
//    - AAG002 (角色ID) - 已有索引 ✓
//
// 5. AA09 (菜单表)
//    - AAI006 (父菜单ID) - 添加索引：用于查询子菜单
//    - AAI009 (菜单类型) - 添加索引：用于按类型筛选菜单
//    - AAI010 (状态) - 添加索引：用于按状态筛选菜单
//    - AAI006+AAI009 (父菜单ID+菜单类型) - 添加联合索引：用于查询特定类型的子菜单
//    - AAI002 (菜单标识) - 已有唯一索引 ✓
//
// 6. AA12 (角色菜单关联表)
//    - AAL001+AAL002 (角色ID+菜单ID) - 添加唯一联合索引：防止重复分配
//    - AAL001 (角色ID) - 已有索引 ✓
//    - AAL002 (菜单ID) - 已有索引 ✓
//
// 7. AA03 (系统日志表)
//    - AAC006 (用户ID) - 添加索引：用于按用户查询日志
//    - AAC004 (操作类型) - 添加索引：用于按操作类型筛选
//    - AAC002+AAC013 (日志级别+日志时间) - 添加联合索引：用于按级别和时间范围查询
//    - AAC002 (日志级别) - 已有索引 ✓
//    - AAC013 (日志时间) - 已有索引 ✓
//
// 8. AA10 (文件表)
//    - AAJ010 (创建人) - 添加索引：用于按创建人查询文件
//    - AAJ005 (存储类型) - 添加索引：用于按存储类型筛选
//    - AAJ009 (文件分类) - 添加索引：用于按分类筛选
//    - AAJ005+AAJ009 (存储类型+分类) - 添加联合索引：用于组合查询
//    - AAJ012 (上传时间) - 添加索引：用于按时间排序和筛选
//
// 9. AA11 (S3配置表)
//    - AAK009 (状态) - 添加索引：用于查询启用的配置
//    - AAK002 (存储类型) - 添加索引：用于按存储类型查询
//    - AAK002+AAK009 (存储类型+状态) - 添加联合索引：用于查询启用的特定类型配置
//
// 10. AA04 (短信验证码表)
//     - AAD002 (手机号) - 已有索引 ✓
//     - AAD004 (验证码类型) - 添加索引：用于按类型筛选
//     - AAD005 (状态) - 添加索引：用于按状态筛选
//     - AAD002+AAD004+AAD005 (手机号+类型+状态) - 添加联合索引：用于查询有效的验证码
//     - AAD006 (过期时间) - 添加索引：用于查询过期验证码
//
// 11. AA08 (短信模板表)
//     - AAH008 (状态) - 添加索引：用于按状态筛选模板
//     - AAH002 (模板类型) - 已有唯一索引 ✓
//
// 12. AA02 (系统配置表)
//     - AAB004 (配置分组) - 添加索引：用于按分组查询配置
//     - AAB006 (状态) - 添加索引：用于按状态筛选配置
//     - AAB004+AAB006 (配置分组+状态) - 添加联合索引：用于查询特定分组的启用配置
